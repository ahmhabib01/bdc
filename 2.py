def long_to_bytes(val):
    h = hex(val)[2:]
    h = '0' * (len(h) % 2) + h
    return bytes.fromhex(h)

def integer_cbrt(n):
    low, high = 0, n
    while low < high:
        mid = (low + high) // 2
        if mid**3 < n:
            low = mid + 1
        else:
            high = mid
    return low

